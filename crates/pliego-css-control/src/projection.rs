#[derive(Serialize)]
struct SourceMapDocument<'a> {
    version: u8,
    sources: &'a [String],
    names: [String; 0],
    mappings: String,
}

#[derive(Clone, Debug, Eq, Ord, PartialEq, PartialOrd)]
struct SourceMapSegment {
    generated_line: usize,
    generated_column: usize,
    source_file: String,
    original_line: usize,
    original_column: usize,
}

struct Utf8Source<'a> {
    text: &'a str,
    line_starts: Vec<usize>,
}

/// Builds a deterministic Source Map v3 from final CSS classes to exact authored snapshots.
///
/// Standard source maps encode one origin per generated segment. This projection therefore selects
/// the first normalized origin that resolves in the exact source ledger; the specialized style
/// manifest remains authoritative for complete many-to-many provenance.
///
/// # Errors
///
/// Returns an error when inputs are duplicate or non-UTF-8, an origin escapes its exact snapshot,
/// a generated class is absent from final CSS, or the canonical document cannot be encoded.
pub fn build_css_source_map(
    css: &str,
    styles: &[SourceMapStyle<'_>],
    inputs: &[AuditSourceInput<'_>],
) -> Result<Vec<u8>, String> {
    let mut source_ledger = BTreeMap::new();
    let mut virtual_source = None;
    for input in inputs {
        let text = std::str::from_utf8(input.bytes).map_err(|error| {
            format!(
                "source-map input `{}` is not valid UTF-8: {error}",
                input.logical_path
            )
        })?;
        let source = Utf8Source {
            text,
            line_starts: line_starts(text),
        };
        if source_ledger.insert(input.logical_path, source).is_some() {
            return Err(format!(
                "source-map input `{}` is duplicated",
                input.logical_path
            ));
        }
        if input.role == "cli-source" && virtual_source.is_none() {
            virtual_source = Some(input.logical_path);
        }
    }
    let generated_lines = line_starts(css);
    let mut segments = Vec::new();
    for style in styles {
        let (source_file, source_offset) =
            select_source_map_origin(style, &source_ledger, virtual_source)?;
        let source = source_ledger
            .get(source_file.as_str())
            .ok_or_else(|| "selected source-map origin escaped the exact ledger".to_owned())?;
        let (original_line, original_column) =
            utf16_position(source.text, &source.line_starts, source_offset)?;
        let needle = format!(".{}", style.class_name);
        let mut matched = false;
        for (generated_offset, _) in css.match_indices(&needle) {
            matched = true;
            let (generated_line, generated_column) =
                utf16_position(css, &generated_lines, generated_offset)?;
            segments.push(SourceMapSegment {
                generated_line,
                generated_column,
                source_file: source_file.clone(),
                original_line,
                original_column,
            });
        }
        if !matched {
            return Err(format!(
                "source-map class `{}` is absent from final CSS",
                style.class_name
            ));
        }
    }
    segments.sort();
    if segments.windows(2).any(|pair| {
        pair[0].generated_line == pair[1].generated_line
            && pair[0].generated_column == pair[1].generated_column
    }) {
        return Err("source-map has conflicting origins at one generated position".to_owned());
    }
    let sources = segments
        .iter()
        .map(|segment| segment.source_file.clone())
        .collect::<BTreeSet<_>>()
        .into_iter()
        .collect::<Vec<_>>();
    let source_indices = sources
        .iter()
        .enumerate()
        .map(|(index, source)| (source.as_str(), index))
        .collect::<BTreeMap<_, _>>();
    let mappings = encode_mappings(&segments, &source_indices)?;
    let mut bytes = serde_json::to_vec(&SourceMapDocument {
        version: 3,
        sources: &sources,
        names: [],
        mappings,
    })
    .map_err(|error| format!("cannot encode canonical CSS source map: {error}"))?;
    bytes.push(b'\n');
    Ok(bytes)
}

fn select_source_map_origin(
    style: &SourceMapStyle<'_>,
    source_ledger: &BTreeMap<&str, Utf8Source<'_>>,
    virtual_source: Option<&str>,
) -> Result<(String, usize), String> {
    if let Some((file, offset)) = style
        .origins
        .iter()
        .filter_map(|origin| Some((origin.file?, origin.byte_start?)))
        .find(|(file, offset)| {
            source_ledger
                .get(file)
                .is_some_and(|source| valid_utf8_offset(source.text, *offset))
        })
    {
        return Ok((file.to_owned(), offset));
    }
    let has_virtual_origin = style
        .origins
        .iter()
        .any(|origin| origin.file.is_none() && origin.byte_start.is_none());
    virtual_source
        .filter(|_| has_virtual_origin)
        .map(|file| (file.to_owned(), 0))
        .ok_or_else(|| {
            format!(
                "source-map class `{}` has no origin in the exact source ledger",
                style.class_name
            )
        })
}

fn line_starts(text: &str) -> Vec<usize> {
    let mut starts = vec![0];
    starts.extend(
        text.as_bytes()
            .iter()
            .enumerate()
            .filter_map(|(index, byte)| (*byte == b'\n').then_some(index + 1)),
    );
    starts
}

fn valid_utf8_offset(text: &str, offset: usize) -> bool {
    offset <= text.len() && text.is_char_boundary(offset)
}

fn utf16_position(text: &str, starts: &[usize], offset: usize) -> Result<(usize, usize), String> {
    if !valid_utf8_offset(text, offset) {
        return Err(format!(
            "source-map byte offset {offset} is outside a UTF-8 character boundary"
        ));
    }
    let line = starts.partition_point(|start| *start <= offset) - 1;
    let column = text[starts[line]..offset].encode_utf16().count();
    Ok((line, column))
}

fn encode_mappings(
    segments: &[SourceMapSegment],
    source_indices: &BTreeMap<&str, usize>,
) -> Result<String, String> {
    let mut output = String::new();
    let mut generated_line = 0usize;
    let mut generated_column = 0i64;
    let mut previous_source = 0i64;
    let mut previous_original_line = 0i64;
    let mut previous_original_column = 0i64;
    let mut first_on_line = true;
    for segment in segments {
        while generated_line < segment.generated_line {
            output.push(';');
            generated_line += 1;
            generated_column = 0;
            first_on_line = true;
        }
        if !first_on_line {
            output.push(',');
        }
        let column = i64::try_from(segment.generated_column)
            .map_err(|_| "source-map generated column exceeds i64".to_owned())?;
        let source_index = source_indices
            .get(segment.source_file.as_str())
            .ok_or_else(|| "source-map segment references an unindexed source".to_owned())?;
        let source = i64::try_from(*source_index)
            .map_err(|_| "source-map source index exceeds i64".to_owned())?;
        let original_line = i64::try_from(segment.original_line)
            .map_err(|_| "source-map original line exceeds i64".to_owned())?;
        let original_column = i64::try_from(segment.original_column)
            .map_err(|_| "source-map original column exceeds i64".to_owned())?;
        encode_vlq(column - generated_column, &mut output);
        encode_vlq(source - previous_source, &mut output);
        encode_vlq(original_line - previous_original_line, &mut output);
        encode_vlq(original_column - previous_original_column, &mut output);
        generated_column = column;
        previous_source = source;
        previous_original_line = original_line;
        previous_original_column = original_column;
        first_on_line = false;
    }
    Ok(output)
}

fn encode_vlq(value: i64, output: &mut String) {
    const BASE64: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut encoded = (value.unsigned_abs() << 1) | u64::from(value.is_negative());
    loop {
        let mut digit = u8::try_from(encoded & 31).expect("base64 VLQ digit fits u8");
        encoded >>= 5;
        if encoded != 0 {
            digit |= 32;
        }
        output.push(char::from(BASE64[usize::from(digit)]));
        if encoded == 0 {
            break;
        }
    }
}

