/// Revalidates the measurement subset that is structurally derivable from canonical graph bytes.
///
/// Resolution-dependent counters must describe at least one complete graph theme because the audit
/// input intentionally carries neither resolver selections nor compiled usage. Coverage depends on
/// that omitted usage set, while contrast pairs belong to separate accessibility analysis, so this
/// helper deliberately does not infer either value.
fn validate_published_token_graph_measurements(
    graph: &TokenGraph,
    bytes: &[u8],
    measurements: &TokenMeasurements,
) -> Result<Vec<AdapterIdentity>, String> {
    if measurements.graph_version.as_deref() != Some(graph.graph_version.as_str()) {
        return Err(
            "published token graph version disagrees with measured token evidence".to_owned(),
        );
    }
    let graph_hash = content_hash(bytes);
    if measurements.graph_hash.as_deref() != Some(graph_hash.as_str()) {
        return Err("published token graph hash disagrees with measured token evidence".to_owned());
    }
    let adapter = graph.adapter.as_ref().map(|adapter| AdapterIdentity {
        name: adapter.name.clone(),
        version: adapter.version.clone(),
    });
    if measurements.dtcg_adapter.as_ref() != adapter.as_ref() {
        return Err(
            "published token graph adapter disagrees with measured token evidence".to_owned(),
        );
    }
    if measurements.themes != count_u64(graph.themes.len(), "theme")? {
        return Err(
            "published token graph theme count disagrees with measured token evidence".into(),
        );
    }
    if measurements.cycles != 0 {
        return Err("canonical token graphs require a measured cycle count of zero".into());
    }

    let source_expressions = graph
        .sources
        .iter()
        .map(|source| (source.path.as_str(), (source.expression, source.deprecated)))
        .collect::<BTreeMap<_, _>>();
    let resolved = graph
        .themes
        .iter()
        .map(|theme| {
            let winning = theme
                .tokens
                .iter()
                .filter_map(|token| token.source.as_deref())
                .collect::<BTreeSet<_>>();
            let mut aliases = 0usize;
            let mut derived_values = 0usize;
            let mut deprecations = 0usize;
            for source in winning {
                let (expression, deprecated) = source_expressions
                    .get(source)
                    .ok_or_else(|| format!("token graph winning source `{source}` is absent"))?;
                aliases += usize::from(*expression == TokenExpression::Alias);
                derived_values += usize::from(*expression == TokenExpression::Derived);
                deprecations += usize::from(*deprecated);
            }
            Ok(ResolvedTokenGraphMeasurements {
                theme,
                tokens: count_u64(theme.tokens.len(), "resolved token")?,
                aliases: count_u64(aliases, "alias")?,
                derived_values: count_u64(derived_values, "derived value")?,
                deprecations: count_u64(deprecations, "deprecated token")?,
            })
        })
        .collect::<Result<Vec<_>, String>>()?;

    let mut candidates = resolved.iter().collect::<Vec<_>>();
    candidates.retain(|candidate| candidate.tokens == measurements.tokens);
    if candidates.is_empty() {
        return Err("published token graph token count matches no resolved theme".into());
    }
    candidates.retain(|candidate| candidate.theme.dtcg_inventory == measurements.dtcg_inventory);
    if candidates.is_empty() {
        return Err("published token graph DTCG inventory matches no resolved theme".into());
    }
    candidates.retain(|candidate| candidate.aliases == measurements.aliases);
    if candidates.is_empty() {
        return Err("published token graph alias count matches no resolved theme".into());
    }
    candidates.retain(|candidate| candidate.derived_values == measurements.derived_values);
    if candidates.is_empty() {
        return Err("published token graph derived-value count matches no resolved theme".into());
    }
    candidates.retain(|candidate| candidate.deprecations == measurements.deprecations);
    if candidates.is_empty() {
        return Err("published token graph deprecation count matches no resolved theme".into());
    }
    Ok(adapter.into_iter().collect())
}

