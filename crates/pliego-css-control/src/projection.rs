#[derive(Clone, Copy)]
/// Complete analyzer evidence required to build one canonical control group.
pub struct AuditControlInput<'a> {
    /// Exact inputs contributing to `sourceHash`.
    pub source_inputs: &'a [AuditSourceInput<'a>],
    /// Exact configuration inputs contributing to `configHash`.
    pub config_inputs: &'a [AuditSourceInput<'a>],
    /// Generated outputs to integrity-bind alongside findings.
    pub generated_outputs: &'a [ControlOutputInput<'a>],
    /// Canonical finding document shared by all renderers.
    pub document: &'a FindingDocument,
    /// Whether the producer's enforced policy passed.
    pub passed: bool,
    /// Measured aggregate CSS metrics, when syntax ingestion succeeded.
    pub rule_metrics: Option<&'a CssBudgetMetrics>,
    /// Honest reason used when rule metrics are unavailable.
    pub rules_unavailable_reason: &'a str,
    /// Measured typed-token evidence or an explicit unavailable state.
    pub token_observation: TokenObservationInput<'a>,
    /// Optional canonical semantic token graph published with the control group.
    pub token_graph: Option<&'a TokenGraph>,
    /// Outputs related to the findings artifact.
    pub output_relationships: &'a [String],
    /// Whether canonical Asset Plan regeneration passed.
    pub asset_plan_verified: bool,
    /// Selected frozen compatibility profile.
    pub targets: CompatibilityProfile,
    /// Optional parsed budget policy.
    pub budget_policy: Option<&'a BudgetPolicy>,
    /// Optional logical budget-policy path.
    pub budget_policy_path: Option<&'a str>,
    /// Optional exact budget-policy bytes.
    pub budget_policy_bytes: Option<&'a [u8]>,
    /// Explicit package or route subjects applied by the audit.
    pub budget_subjects: &'a [BudgetSubject],
}

/// Borrowed canonical artifact emitted by a completed control group.
pub struct ControlArtifact<'a> {
    /// Fixed artifact filename.
    pub file: &'static str,
    /// Canonical artifact bytes.
    pub bytes: &'a [u8],
}

/// Canonical findings, control manifest, and receipt built from one evidence snapshot.
pub struct AuditControlGroup {
    token_graph: Option<Vec<u8>>,
    findings: Vec<u8>,
    manifest: Vec<u8>,
    receipt: Vec<u8>,
}

impl AuditControlGroup {
    /// Iterates over canonical artifacts in publication order.
    ///
    /// The optional token graph is published first so every later control artifact can refer to
    /// bytes that already exist. Legacy groups without a graph preserve their three-artifact order.
    pub fn artifacts(&self) -> impl Iterator<Item = ControlArtifact<'_>> {
        self.token_graph
            .iter()
            .map(|bytes| ControlArtifact {
                file: TOKEN_GRAPH_FILE,
                bytes,
            })
            .chain([
                ControlArtifact {
                    file: FINDINGS_FILE,
                    bytes: &self.findings,
                },
                ControlArtifact {
                    file: CONTROL_MANIFEST_FILE,
                    bytes: &self.manifest,
                },
                ControlArtifact {
                    file: BUILD_RECEIPT_FILE,
                    bytes: &self.receipt,
                },
            ])
    }
}

