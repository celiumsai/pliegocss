    #[test]
    fn advanced_graph_preserves_alias_identity_and_transitive_coverage() {
        let literal = pliego_css_config::parse_dtcg_str(
            r#"{
              "color": {
                "$type": "color",
                "brand": {"$value": {"colorSpace": "srgb", "components": [0.2, 0.4, 0.8]}},
                "action": {"$value": {"colorSpace": "srgb", "components": [0.2, 0.4, 0.8]}}
              }
            }"#,
        )
        .expect("literal DTCG graph");
        let alias = pliego_css_config::parse_dtcg_str(
            r#"{
              "color": {
                "$type": "color",
                "brand": {"$value": {"colorSpace": "srgb", "components": [0.2, 0.4, 0.8]}},
                "action": {"$value": "{color.brand}", "$deprecated": "Use color.brand"}
              }
            }"#,
        )
        .expect("alias DTCG graph");
        assert_eq!(literal.registry().id(), alias.registry().id());
        let action = alias
            .registry()
            .token_by_name(TokenKind::Color, "action")
            .expect("action token");
        let used = BTreeSet::from([FlatTokenReference::new(TokenKind::Color, action.id)]);
        let selections = BTreeMap::new();
        let literal_measurements =
            build_token_graph_measurements(literal.graph(), &selections, literal.registry(), &used)
                .expect("literal measurements");
        let alias_measurements =
            build_token_graph_measurements(alias.graph(), &selections, alias.registry(), &used)
                .expect("alias measurements");
        let unused_alias = build_token_graph_measurements(
            alias.graph(),
            &selections,
            alias.registry(),
            &BTreeSet::new(),
        )
        .expect("unused alias measurements");

        assert_ne!(
            literal_measurements.graph_hash,
            alias_measurements.graph_hash
        );
        assert_eq!(literal_measurements.aliases, 0);
        assert_eq!(alias_measurements.aliases, 1);
        assert_eq!(alias_measurements.deprecations, 1);
        assert!(
            alias_measurements.coverage_basis_points > literal_measurements.coverage_basis_points
        );
        assert_eq!(alias_measurements.graph_hash, unused_alias.graph_hash);
        assert_eq!(unused_alias.coverage_basis_points, Some(0));
        assert_eq!(
            alias_measurements
                .dtcg_adapter
                .as_ref()
                .map(|adapter| (adapter.name.as_str(), adapter.version.as_str())),
            Some(("dtcg", "2025.10"))
        );
    }

