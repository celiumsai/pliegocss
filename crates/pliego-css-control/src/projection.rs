#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
struct FlatTokenGraph<'a> {
    schema_version: u8,
    tokens: Vec<FlatTokenNode<'a>>,
}

#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
struct FlatTokenNode<'a> {
    kind: &'static str,
    token_id: String,
    name: &'a str,
    value: &'a str,
}

/// Projects one active flat registry plus retained references into measured control evidence.
///
/// # Errors
///
/// Returns an error when a retained reference is absent from the registry, a count cannot fit the
/// wire contract, or the canonical graph cannot be encoded.
pub fn build_flat_token_measurements(
    theme: &ThemeRegistry,
    used: &BTreeSet<FlatTokenReference>,
) -> Result<TokenMeasurements, String> {
    let declared = theme
        .tokens()
        .iter()
        .map(|token| FlatTokenReference::new(token.kind, token.id))
        .collect::<BTreeSet<_>>();
    if !used.is_subset(&declared) {
        return Err("compiled token usage escaped the active typed registry".into());
    }
    let graph = FlatTokenGraph {
        schema_version: 1,
        tokens: theme
            .tokens()
            .iter()
            .map(|token| FlatTokenNode {
                kind: token_kind_name(token.kind),
                token_id: format!("{:08x}", token.id.get()),
                name: &token.name,
                value: &token.value,
            })
            .collect(),
    };
    let graph = serde_json::to_vec(&graph)
        .map_err(|error| format!("cannot encode flat token graph: {error}"))?;
    let tokens =
        u64::try_from(declared.len()).map_err(|_| "declared token count exceeds u64".to_owned())?;
    let used = u64::try_from(used.len()).map_err(|_| "used token count exceeds u64".to_owned())?;
    let coverage = u16::try_from(
        used.saturating_mul(10_000)
            .checked_div(tokens)
            .unwrap_or_default(),
    )
    .map_err(|_| "token coverage exceeds 10000 basis points".to_owned())?;
    Ok(TokenMeasurements {
        observation: MeasurementState::Measured,
        unavailable_reason: None,
        graph_version: Some("pliegocss-flat-token-graph/1".to_owned()),
        graph_hash: Some(content_hash(&graph)),
        tokens,
        aliases: 0,
        derived_values: 0,
        themes: 1,
        coverage_basis_points: Some(coverage),
        cycles: 0,
        contrast_pairs: 0,
        deprecations: 0,
        dtcg_adapter: None,
        dtcg_inventory: BTreeMap::new(),
    })
}

/// Projects a canonical internal token graph plus one exact resolution into measured evidence.
///
/// Coverage follows retained token references through the winning alias/derived dependency graph.
/// The graph hash excludes build usage, so changing only retained styles changes coverage without
/// changing graph identity.
///
/// # Errors
///
/// Returns an error when the graph is noncanonical, the selected resolution disagrees with the
/// active registry, a dependency projection is malformed, or compiled usage escapes the registry.
pub fn build_token_graph_measurements(
    graph: &TokenGraph,
    selections: &BTreeMap<String, String>,
    theme: &ThemeRegistry,
    used: &BTreeSet<FlatTokenReference>,
) -> Result<TokenMeasurements, String> {
    let graph_bytes = graph
        .to_canonical_json()
        .map_err(|error| format!("cannot encode token graph: {error}"))?;
    let resolution = graph
        .theme(selections)
        .ok_or_else(|| "token graph has no theme for the selected resolver inputs".to_owned())?;
    let theme_id = format!("{:032x}", theme.id().get());
    if resolution.theme_id != theme_id {
        return Err("token graph resolution disagrees with the active ThemeId".into());
    }
    let declared = theme
        .tokens()
        .iter()
        .map(|token| FlatTokenReference::new(token.kind, token.id))
        .collect::<BTreeSet<_>>();
    if !used.is_subset(&declared) {
        return Err("compiled token usage escaped the active typed registry".into());
    }
    validate_resolved_graph_tokens(resolution, theme)?;
    let coverage = graph_coverage(graph, resolution, &declared, used)?;
    let tokens = count_u64(declared.len(), "declared token")?;
    let covered = count_u64(coverage.covered, "covered token")?;
    let coverage_basis_points = u16::try_from(
        covered
            .saturating_mul(10_000)
            .checked_div(tokens)
            .unwrap_or_default(),
    )
    .map_err(|_| "token coverage exceeds 10000 basis points".to_owned())?;
    Ok(TokenMeasurements {
        observation: MeasurementState::Measured,
        unavailable_reason: None,
        graph_version: Some(graph.graph_version.clone()),
        graph_hash: Some(content_hash(&graph_bytes)),
        tokens,
        aliases: count_u64(coverage.aliases, "alias")?,
        derived_values: count_u64(coverage.derived_values, "derived value")?,
        themes: count_u64(graph.themes.len(), "theme")?,
        coverage_basis_points: Some(coverage_basis_points),
        cycles: 0,
        contrast_pairs: 0,
        deprecations: count_u64(coverage.deprecations, "deprecated token")?,
        dtcg_adapter: graph.adapter.as_ref().map(|adapter| AdapterIdentity {
            name: adapter.name.clone(),
            version: adapter.version.clone(),
        }),
        dtcg_inventory: resolution.dtcg_inventory.clone(),
    })
}

/// Projects a canonical token graph as audit evidence without claiming generated-style coverage.
///
/// Unlike [`build_token_graph_measurements`], a standards-CSS audit has no compiler-owned token-use
/// set or single active theme. This projection therefore counts the union of declared projected
/// tokens across every validated theme, records zero coverage, and carries the number of explicit
/// contrast relationships evaluated by the accessibility policy. It never infers token use from
/// CSS custom-property spelling.
///
/// # Errors
///
/// Returns an error when canonical graph serialization or any count exceeds its wire type.
pub fn build_audit_token_graph_measurements(
    graph: &TokenGraph,
    contrast_pairs: u64,
) -> Result<TokenMeasurements, String> {
    let graph_bytes = graph
        .to_canonical_json()
        .map_err(|error| format!("cannot encode audit token graph: {error}"))?;
    let declared = graph
        .themes
        .iter()
        .flat_map(|theme| &theme.tokens)
        .map(|token| (token.kind.as_str(), token.token_id.as_str()))
        .collect::<BTreeSet<_>>();
    Ok(TokenMeasurements {
        observation: MeasurementState::Measured,
        unavailable_reason: None,
        graph_version: Some(graph.graph_version.clone()),
        graph_hash: Some(content_hash(&graph_bytes)),
        tokens: count_u64(declared.len(), "audit declared token")?,
        aliases: graph.aliases(),
        derived_values: graph.derived_values(),
        themes: count_u64(graph.themes.len(), "audit token theme")?,
        coverage_basis_points: Some(0),
        cycles: 0,
        contrast_pairs,
        deprecations: graph.deprecations(),
        dtcg_adapter: graph.adapter.as_ref().map(|adapter| AdapterIdentity {
            name: adapter.name.clone(),
            version: adapter.version.clone(),
        }),
        dtcg_inventory: graph.dtcg_inventory.clone(),
    })
}

struct GraphCoverage {
    covered: usize,
    aliases: usize,
    derived_values: usize,
    deprecations: usize,
}

fn graph_coverage(
    graph: &TokenGraph,
    resolution: &pliego_css_config::TokenGraphTheme,
    declared: &BTreeSet<FlatTokenReference>,
    used: &BTreeSet<FlatTokenReference>,
) -> Result<GraphCoverage, String> {
    let sources = graph
        .sources
        .iter()
        .map(|source| (source.path.as_str(), source))
        .collect::<BTreeMap<_, _>>();
    let token_sources = resolution
        .tokens
        .iter()
        .filter_map(|token| {
            token.source.as_deref().map(|source| {
                projected_reference_fields(&token.kind, &token.token_id)
                    .map(|reference| (reference, source))
            })
        })
        .collect::<Result<BTreeMap<_, _>, _>>()?;
    let mut covered = used.clone();
    let mut pending = used
        .iter()
        .filter_map(|reference| token_sources.get(reference).copied())
        .collect::<Vec<_>>();
    let mut visited_sources = BTreeSet::new();
    while let Some(path) = pending.pop() {
        if !visited_sources.insert(path) {
            continue;
        }
        let source = sources
            .get(path)
            .ok_or_else(|| format!("token graph winning source `{path}` is absent"))?;
        for edge in &source.references {
            let Some(target) = edge.target.as_deref() else {
                continue;
            };
            pending.push(target);
            let target_source = sources
                .get(target)
                .ok_or_else(|| format!("token graph dependency source `{target}` is absent"))?;
            if let Some(projection) = &target_source.projection {
                let reference = projected_reference(projection)?;
                if declared.contains(&reference) {
                    covered.insert(reference);
                }
            }
        }
    }
    let winning = resolution
        .tokens
        .iter()
        .filter_map(|token| token.source.as_deref())
        .collect::<BTreeSet<_>>();
    Ok(GraphCoverage {
        covered: covered.len(),
        aliases: graph
            .sources
            .iter()
            .filter(|source| {
                winning.contains(source.path.as_str())
                    && source.expression == TokenExpression::Alias
            })
            .count(),
        derived_values: graph
            .sources
            .iter()
            .filter(|source| {
                winning.contains(source.path.as_str())
                    && source.expression == TokenExpression::Derived
            })
            .count(),
        deprecations: graph
            .sources
            .iter()
            .filter(|source| winning.contains(source.path.as_str()) && source.deprecated)
            .count(),
    })
}

fn validate_resolved_graph_tokens(
    resolution: &pliego_css_config::TokenGraphTheme,
    theme: &ThemeRegistry,
) -> Result<(), String> {
    if resolution.tokens.len() != theme.tokens().len() {
        return Err("token graph resolution has a different token count than the registry".into());
    }
    for token in &resolution.tokens {
        let reference = projected_reference_fields(&token.kind, &token.token_id)?;
        let resolved = theme
            .token_by_id(reference.kind, reference.id)
            .ok_or_else(|| format!("token graph contains absent token `{}`", token.name))?;
        if resolved.name != token.name || resolved.value != token.value {
            return Err(format!(
                "token graph value for `{}.{}` disagrees with the active registry",
                token.kind, token.name
            ));
        }
    }
    Ok(())
}

fn projected_reference(projection: &TokenGraphProjection) -> Result<FlatTokenReference, String> {
    projected_reference_fields(&projection.kind, &projection.token_id)
}

fn projected_reference_fields(kind: &str, token_id: &str) -> Result<FlatTokenReference, String> {
    let kind = token_kind_from_name(kind)
        .ok_or_else(|| format!("token graph contains unknown token kind `{kind}`"))?;
    let id = u32::from_str_radix(token_id, 16)
        .map_err(|_| format!("token graph contains invalid token ID `{token_id}`"))?;
    Ok(FlatTokenReference::new(kind, TokenId::new(id)))
}

fn count_u64(value: usize, label: &str) -> Result<u64, String> {
    u64::try_from(value).map_err(|_| format!("{label} count exceeds u64"))
}

