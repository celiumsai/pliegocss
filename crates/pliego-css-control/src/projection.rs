#[allow(clippy::too_many_lines)]
/// Builds and validates one canonical audit/build control group.
///
/// # Errors
///
/// Returns an error when evidence is incomplete, inconsistent, or cannot satisfy the closed
/// control-artifact contract.
pub fn build_audit_control_group(
    input: AuditControlInput<'_>,
) -> Result<AuditControlGroup, String> {
    if input.source_inputs.is_empty() {
        return Err("audit control group requires at least one source input".to_owned());
    }
    match (
        input.budget_policy,
        input.budget_policy_path,
        input.budget_policy_bytes,
    ) {
        (Some(_), Some(_), Some(_)) | (None, None, None) => {}
        _ => {
            return Err(
                "audit budget policy, logical path, and exact bytes must be supplied together"
                    .to_owned(),
            );
        }
    }
    let (token_graph, adapters) = if let Some(graph) = input.token_graph {
        if input
            .generated_outputs
            .iter()
            .any(|output| output.file == TOKEN_GRAPH_FILE)
        {
            return Err(format!(
                "generated outputs cannot claim reserved token-graph path `{TOKEN_GRAPH_FILE}`"
            ));
        }
        let bytes = graph
            .to_canonical_json()
            .map_err(|error| format!("cannot encode canonical token graph: {error}"))?;
        parse_token_graph(&bytes)
            .map_err(|error| format!("cannot validate canonical token graph: {error}"))?;
        let measurements = match input.token_observation {
            TokenObservationInput::Measured(measurements) => measurements,
            TokenObservationInput::Unavailable(_) => {
                return Err("a published token graph requires measured token evidence".to_owned());
            }
        };
        let adapters = validate_published_token_graph_measurements(graph, &bytes, measurements)?;
        (Some(bytes), adapters)
    } else {
        (None, Vec::new())
    };
    let findings = input
        .document
        .to_json_pretty()
        .map_err(|error| error.to_string())?
        .into_bytes();
    let finding_value: Value = serde_json::from_slice(&findings)
        .map_err(|error| format!("cannot inspect canonical finding document: {error}"))?;
    let finding_summary = summarize_findings(&finding_value)?;
    let compatibility_policy = build_compatibility_policy(input.targets)?;
    let compatibility_value: Value = serde_json::from_str(&compatibility_policy)
        .map_err(|error| format!("cannot inspect compatibility policy: {error}"))?;
    let compatibility_hash = content_hash(compatibility_policy.as_bytes());
    let budget_policy_json = input
        .budget_policy
        .map(BudgetPolicy::to_json_pretty)
        .transpose()
        .map_err(|error| error.to_string())?;
    let budget_policy_hash = budget_policy_json
        .as_deref()
        .map(str::as_bytes)
        .map(content_hash);
    let mut subjects = input
        .budget_subjects
        .iter()
        .map(|subject| format!("{}={}", subject.kind().as_str(), subject.id()))
        .collect::<Vec<_>>();
    subjects.sort();
    subjects.dedup();
    let policy_identity = ConfigIdentity {
        target_profile: input.targets.as_str(),
        compatibility_policy_sha256: &compatibility_hash,
        budget_policy_sha256: budget_policy_hash.as_deref(),
        budget_subjects: &subjects,
    };
    let mut config_files = input
        .config_inputs
        .iter()
        .map(|source| InputFile {
            file: source.logical_path.to_owned(),
            role: source.role.to_owned(),
            sha256: content_hash(source.bytes),
        })
        .collect::<Vec<_>>();
    config_files.sort_by(|left, right| left.file.cmp(&right.file));
    let config_file_identities = config_files
        .iter()
        .map(|source| SourceSetIdentity {
            file: &source.file,
            sha256: &source.sha256,
        })
        .collect::<Vec<_>>();
    let config_identity = if config_file_identities.is_empty() {
        serde_json::to_vec(&policy_identity)
    } else {
        serde_json::to_vec(&ConfigSetIdentity {
            policy: &policy_identity,
            files: &config_file_identities,
        })
    }
    .map_err(|error| format!("cannot hash audit configuration: {error}"))?;
    let config_hash = content_hash(&config_identity);
    let mut input_files = input
        .source_inputs
        .iter()
        .map(|source| InputFile {
            file: source.logical_path.to_owned(),
            role: source.role.to_owned(),
            sha256: content_hash(source.bytes),
        })
        .collect::<Vec<_>>();
    input_files.sort_by(|left, right| left.file.cmp(&right.file));
    let source_identities = input_files
        .iter()
        .map(|source| SourceSetIdentity {
            file: &source.file,
            sha256: &source.sha256,
        })
        .collect::<Vec<_>>();
    let source_set = serde_json::to_vec(&source_identities)
        .map_err(|error| format!("cannot hash audit source set: {error}"))?;

    let finding_reference = ArtifactReference::from_bytes(FINDINGS_FILE, &findings)
        .map_err(|error| error.to_string())?;
    let token_graph_reference = token_graph
        .as_deref()
        .map(|bytes| ArtifactReference::from_bytes(TOKEN_GRAPH_FILE, bytes))
        .transpose()
        .map_err(|error| error.to_string())?;
    let mut token_graph_relationships = input
        .generated_outputs
        .iter()
        .filter(|output| matches!(output.role, "generated-css" | "style-manifest"))
        .map(|output| output.file.to_owned())
        .collect::<Vec<_>>();
    token_graph_relationships.sort();
    token_graph_relationships.dedup();
    let mut outputs = Vec::with_capacity(
        input.generated_outputs.len() + 1 + usize::from(token_graph_reference.is_some()),
    );
    for output in input.generated_outputs {
        let mut relationships = output.relationships.to_vec();
        if token_graph_reference.is_some()
            && matches!(output.role, "generated-css" | "style-manifest")
        {
            relationships.push(TOKEN_GRAPH_FILE.to_owned());
        }
        relationships.sort();
        relationships.dedup();
        outputs.push(OutputArtifact {
            artifact: ArtifactReference::from_bytes(output.file, output.bytes)
                .map_err(|error| error.to_string())?,
            role: output.role.to_owned(),
            media_type: output.media_type.to_owned(),
            source_map: output
                .source_map
                .map(|source_map| ArtifactReference::from_bytes(source_map.file, source_map.bytes))
                .transpose()
                .map_err(|error| error.to_string())?,
            relationships,
        });
    }
    if let Some(reference) = &token_graph_reference {
        outputs.push(OutputArtifact {
            artifact: reference.clone(),
            role: "token-graph".to_owned(),
            media_type: "application/json".to_owned(),
            source_map: None,
            relationships: token_graph_relationships,
        });
    }
    let rules = rules(input.rule_metrics, input.rules_unavailable_reason)?;
    let decisions = decisions(&finding_value)?;
    let decision_summary = summarize_decisions(&decisions)?;
    let targets = targets(&compatibility_value)?;
    let tool = tool(
        &finding_value,
        &compatibility_value,
        input.budget_policy.is_some(),
        input.asset_plan_verified,
    )?;
    let backend = backend(&finding_value, &compatibility_hash)?;
    let checks = checks(
        &input,
        &finding_summary,
        input.rule_metrics.is_some(),
        token_graph_reference.as_ref(),
    );
    let required_checks = checks
        .iter()
        .filter(|check| check.required)
        .map(|check| check.id.clone())
        .collect::<Vec<_>>();
    let result = if input.passed && finding_summary.unexcepted_errors == 0 {
        ReceiptResult::Passed
    } else {
        ReceiptResult::Failed
    };
    input_files.extend(config_files);
    if let (Some(path), Some(bytes)) = (input.budget_policy_path, input.budget_policy_bytes) {
        input_files.push(InputFile {
            file: path.to_owned(),
            role: "policy".to_owned(),
            sha256: content_hash(bytes),
        });
    }
    input_files.sort_by(|left, right| left.file.cmp(&right.file));
    let mut output_relationships = input.output_relationships.to_vec();
    if token_graph_reference.is_some() {
        output_relationships.push(TOKEN_GRAPH_FILE.to_owned());
    }
    output_relationships.sort();
    output_relationships.dedup();
    outputs.push(OutputArtifact {
        artifact: finding_reference.clone(),
        role: "audit-findings".to_owned(),
        media_type: "application/json".to_owned(),
        source_map: None,
        relationships: output_relationships,
    });
    outputs.sort_by(|left, right| left.artifact.file.cmp(&right.artifact.file));
    let receipt_outputs = outputs
        .iter()
        .map(|output| output.artifact.clone())
        .collect();

    let manifest = ControlManifest {
        document_kind: CONTROL_MANIFEST_KIND.to_owned(),
        schema_version: CONTROL_SCHEMA_VERSION.to_owned(),
        tool: tool.clone(),
        inputs: ManifestInputs {
            source_root: "workspace".to_owned(),
            source_hash: content_hash(&source_set),
            config_hash: config_hash.clone(),
            files: input_files,
            source_manifest: None,
            project_index: None,
            adapters,
        },
        backend: backend.clone(),
        targets: targets.clone(),
        outputs,
        rules,
        tokens: match input.token_observation {
            TokenObservationInput::Measured(measurements) => measurements.clone(),
            TokenObservationInput::Unavailable(reason) => TokenMeasurements {
                observation: MeasurementState::Unavailable,
                unavailable_reason: Some(reason.to_owned()),
                graph_version: None,
                graph_hash: None,
                tokens: 0,
                aliases: 0,
                derived_values: 0,
                themes: 0,
                coverage_basis_points: None,
                cycles: 0,
                contrast_pairs: 0,
                deprecations: 0,
                dtcg_adapter: None,
                dtcg_inventory: BTreeMap::new(),
            },
        },
        decisions,
        violations: ViolationSummary {
            finding_schema_version: FINDING_SCHEMA_VERSION.to_owned(),
            document: finding_reference.clone(),
            counts_by_code: finding_summary.counts_by_code,
            counts_by_severity: finding_summary.counts_by_severity,
            counts_by_verification: finding_summary.counts_by_verification,
            active_exception_ids: finding_summary.active_exceptions.clone(),
            parity_passed: true,
        },
        receipt: ReceiptExpectation {
            schema_version: CONTROL_SCHEMA_VERSION.to_owned(),
            file: BUILD_RECEIPT_FILE.to_owned(),
            required_checks,
            expected_result: result,
        },
    };
    let manifest_bytes = manifest
        .to_canonical_json()
        .map_err(|error| error.to_string())?;
    let receipt = BuildReceipt {
        document_kind: BUILD_RECEIPT_KIND.to_owned(),
        schema_version: CONTROL_SCHEMA_VERSION.to_owned(),
        tool,
        inputs: ReceiptInputs {
            source_hash: manifest.inputs.source_hash.clone(),
            config_hash,
        },
        backend,
        targets,
        manifest: ArtifactReference::from_bytes(CONTROL_MANIFEST_FILE, &manifest_bytes)
            .map_err(|error| error.to_string())?,
        outputs: receipt_outputs,
        decisions: decision_summary,
        findings: ReceiptFindingSummary {
            document: finding_reference,
            total: finding_summary.total,
            unexcepted_errors: finding_summary.unexcepted_errors,
            active_exception_ids: finding_summary.active_exceptions,
        },
        checks,
        result,
    };
    let receipt = receipt
        .to_canonical_json(&manifest_bytes)
        .map_err(|error| error.to_string())?;
    Ok(AuditControlGroup {
        token_graph,
        findings,
        manifest: manifest_bytes,
        receipt,
    })
}

fn rules(
    metrics: Option<&CssBudgetMetrics>,
    unavailable_reason: &str,
) -> Result<RuleMeasurements, String> {
    let Some(metrics) = metrics else {
        return Ok(RuleMeasurements {
            observation: MeasurementState::Unavailable,
            unavailable_reason: Some(unavailable_reason.to_owned()),
            total_bytes: 0,
            rules: 0,
            selectors: 0,
            declarations: 0,
            maximum_specificity: None,
            semantic_duplicates: 0,
            by_layer: BTreeMap::new(),
            by_package: BTreeMap::new(),
            by_route: BTreeMap::new(),
            by_component: BTreeMap::new(),
            by_state: BTreeMap::new(),
            by_rule_type: BTreeMap::new(),
        });
    };
    let rules = usize_to_u64("rules", metrics.rules())?;
    let unknown = BTreeMap::from([("unknown".to_owned(), rules)]);
    Ok(RuleMeasurements {
        observation: MeasurementState::Measured,
        unavailable_reason: None,
        total_bytes: usize_to_u64("canonical bytes", metrics.canonical_bytes())?,
        rules,
        selectors: usize_to_u64("selectors", metrics.selectors())?,
        declarations: usize_to_u64("declarations", metrics.declarations())?,
        maximum_specificity: Some(
            CssSpecificity::from_packed(metrics.max_specificity()).to_string(),
        ),
        semantic_duplicates: usize_to_u64("semantic duplicates", metrics.semantic_duplicates())?,
        by_layer: unknown.clone(),
        by_package: unknown.clone(),
        by_route: unknown.clone(),
        by_component: unknown.clone(),
        by_state: unknown.clone(),
        by_rule_type: unknown,
    })
}

fn targets(policy: &Value) -> Result<TargetIdentity, String> {
    let root = object(policy, "compatibility policy")?;
    let data = object(field(root, "compatibilityData")?, "compatibilityData")?;
    let web_features = object(field(data, "webFeatures")?, "webFeatures")?;
    let browsers = array(field(root, "browserTargets")?, "browserTargets")?
        .iter()
        .map(|target| {
            let target = object(target, "browser target")?;
            Ok(format!(
                "{}>={}",
                string(target, "id")?,
                string(target, "minimum")?
            ))
        })
        .collect::<Result<Vec<_>, String>>()?;
    let reset = object(field(root, "reset")?, "reset")?;
    let scope = object(field(root, "scope")?, "scope")?;
    Ok(TargetIdentity {
        profile: string(root, "profile")?.to_owned(),
        browsers,
        compatibility: CompatibilityData {
            source: string(web_features, "name")?.to_owned(),
            version: string(web_features, "version")?.to_owned(),
            date: string(data, "capturedOn")?.to_owned(),
        },
        reset_policy: format!(
            "{}.{}.{}.{}",
            string(reset, "profile")?,
            string(reset, "action")?,
            if boolean(reset, "implicit")? {
                "implicit"
            } else {
                "explicit"
            },
            string(reset, "ownership")?
        ),
        scope_policy: format!(
            "{}.{}.{}",
            string(scope, "profile")?,
            string(scope, "action")?,
            string(scope, "boundary")?
        ),
        capability_decisions_version: number(root, "policyVersion")?.to_string(),
    })
}

fn tool(
    findings: &Value,
    compatibility_policy: &Value,
    has_budget_policy: bool,
    has_asset_plan: bool,
) -> Result<ToolIdentity, String> {
    let root = object(findings, "finding document")?;
    let finding_tool = object(field(root, "tool")?, "finding tool")?;
    let compatibility_policy = object(compatibility_policy, "compatibility policy")?;
    let mut contracts = BTreeMap::from([
        ("control".to_owned(), CONTROL_SCHEMA_VERSION.to_owned()),
        (
            "finding".to_owned(),
            string(root, "schemaVersion")?.to_owned(),
        ),
        (
            "compatibility-policy".to_owned(),
            number(compatibility_policy, "policyVersion")?.to_string(),
        ),
    ]);
    if has_budget_policy {
        contracts.insert("budget-policy".to_owned(), "1".to_owned());
    }
    if has_asset_plan {
        contracts.insert("asset-plan".to_owned(), "1".to_owned());
    }
    if let Some(version) = first_context(findings, "accessibility-policy-version") {
        contracts.insert("accessibility-policy".to_owned(), version.to_owned());
    }
    if let Some(classifier) = first_context(findings, "classifier-version") {
        contracts.insert("classifier".to_owned(), classifier.to_owned());
    }
    Ok(ToolIdentity {
        name: string(finding_tool, "name")?.to_owned(),
        version: string(finding_tool, "version")?.to_owned(),
        contracts,
    })
}

fn backend(findings: &Value, config_hash: &str) -> Result<BackendIdentity, String> {
    let mut stages = vec![
        "budget-analysis".to_owned(),
        "compatibility-classifier".to_owned(),
        "parse".to_owned(),
    ];
    if first_context(findings, "accessibility-policy-version").is_some() {
        stages.insert(0, "accessibility-analysis".to_owned());
    }
    Ok(BackendIdentity {
        name: first_context(findings, "backend")
            .ok_or_else(|| "canonical findings omit the CSS backend identity".to_owned())?
            .to_owned(),
        version: first_context(findings, "backend-version")
            .ok_or_else(|| "canonical findings omit the CSS backend version".to_owned())?
            .to_owned(),
        stages,
        config_hash: config_hash.to_owned(),
    })
}

fn decisions(document: &Value) -> Result<Vec<Decision>, String> {
    let root = object(document, "finding document")?;
    let mut decisions = BTreeMap::<String, Decision>::new();
    for finding in array(field(root, "findings")?, "findings")? {
        let finding = object(finding, "finding")?;
        let code = string(finding, "code")?;
        let context = object(field(finding, "context")?, "finding context")?;
        let action = match code {
            "PCSS-COMPAT-100" => DecisionAction::Preserved,
            "PCSS-COMPAT-101" => DecisionAction::Blocked,
            "PCSS-COMPAT-199" if string(finding, "severity")? == "error" => DecisionAction::Blocked,
            "PCSS-COMPAT-102" | "PCSS-COMPAT-199" => DecisionAction::Degraded,
            _ => continue,
        };
        let fingerprint = string(finding, "fingerprint")?;
        let feature = context
            .get("feature-id")
            .or_else(|| context.get("syntax"))
            .and_then(Value::as_str)
            .unwrap_or("unclassified-css")
            .to_owned();
        let stable = context
            .get("feature-id")
            .or_else(|| context.get("syntax"))
            .and_then(Value::as_str)
            .map_or_else(
                || fingerprint.trim_start_matches("sha256:").to_owned(),
                sanitize_id,
            );
        let evidence = array(field(finding, "evidence")?, "finding evidence")?
            .iter()
            .map(|evidence| {
                let evidence = object(evidence, "evidence")?;
                Ok(format!(
                    "{}.{}",
                    string(evidence, "kind")?,
                    string(evidence, "name")?
                ))
            })
            .collect::<Result<BTreeSet<_>, String>>()?
            .into_iter()
            .collect();
        let id = format!("compat.{stable}");
        let mut decision = Decision {
            id: id.clone(),
            feature,
            action,
            reason: string(finding, "message")?.to_owned(),
            evidence,
            affected_outputs: Vec::new(),
            fingerprint: String::new(),
        };
        decision
            .refresh_fingerprint()
            .map_err(|error| error.to_string())?;
        if let Some(existing) = decisions.get_mut(&id) {
            if existing.feature != decision.feature
                || existing.action != decision.action
                || existing.reason != decision.reason
            {
                return Err(format!(
                    "compatibility decision `{id}` has inconsistent repeated findings"
                ));
            }
            existing.evidence.extend(decision.evidence);
            existing.evidence.sort();
            existing.evidence.dedup();
            existing
                .refresh_fingerprint()
                .map_err(|error| error.to_string())?;
        } else {
            decisions.insert(id, decision);
        }
    }
    Ok(decisions.into_values().collect())
}

fn summarize_findings(document: &Value) -> Result<FindingSummary, String> {
    let root = object(document, "finding document")?;
    let mut summary = FindingSummary {
        counts_by_code: BTreeMap::new(),
        counts_by_severity: BTreeMap::new(),
        counts_by_verification: BTreeMap::new(),
        active_exceptions: Vec::new(),
        unexcepted_errors: 0,
        unexcepted_error_categories: BTreeSet::new(),
        total: 0,
    };
    for finding in array(field(root, "findings")?, "findings")? {
        let finding = object(finding, "finding")?;
        increment(&mut summary.counts_by_code, string(finding, "code")?)?;
        increment(
            &mut summary.counts_by_severity,
            string(finding, "severity")?,
        )?;
        increment(
            &mut summary.counts_by_verification,
            string(finding, "verification")?,
        )?;
        summary.total = summary
            .total
            .checked_add(1)
            .ok_or_else(|| "finding total overflows u64".to_owned())?;
        let exception = finding.get("exception").filter(|value| !value.is_null());
        if let Some(exception) = exception {
            summary
                .active_exceptions
                .push(string(object(exception, "finding exception")?, "id")?.to_owned());
        } else if string(finding, "severity")? == "error" {
            summary.unexcepted_errors = summary
                .unexcepted_errors
                .checked_add(1)
                .ok_or_else(|| "unexcepted error count overflows u64".to_owned())?;
            summary
                .unexcepted_error_categories
                .insert(string(finding, "category")?.to_owned());
        }
    }
    summary.active_exceptions.sort();
    summary.active_exceptions.dedup();
    Ok(summary)
}

fn summarize_decisions(decisions: &[Decision]) -> Result<ReceiptDecisionSummary, String> {
    let mut by_action = BTreeMap::new();
    for decision in decisions {
        let action = serde_json::to_value(decision.action)
            .map_err(|error| format!("cannot summarize decision action: {error}"))?;
        increment(
            &mut by_action,
            action
                .as_str()
                .ok_or_else(|| "decision action did not serialize as a string".to_owned())?,
        )?;
    }
    Ok(ReceiptDecisionSummary {
        total: u64::try_from(decisions.len())
            .map_err(|_| "decision total exceeds u64".to_owned())?,
        by_action,
    })
}

fn checks(
    input: &AuditControlInput<'_>,
    summary: &FindingSummary,
    syntax_measured: bool,
    token_graph: Option<&ArtifactReference>,
) -> Vec<ReceiptCheck> {
    let mut checks = vec![
        check("audit-policy", input.passed),
        check("css-analysis", syntax_measured),
        check("finding-parity", true),
        check("integrity", true),
    ];
    if input.budget_policy.is_some() {
        checks.push(check(
            "budget-policy",
            !summary.unexcepted_error_categories.contains("budget"),
        ));
    }
    if input.asset_plan_verified {
        checks.push(check("asset-plan-integrity", true));
    }
    if let Some(token_graph) = token_graph {
        checks.push(ReceiptCheck {
            id: "token-graph-integrity".to_owned(),
            status: CheckStatus::Passed,
            evidence_kind: "integrity".to_owned(),
            evidence_artifact: Some(token_graph.clone()),
            required: true,
        });
    }
    checks.sort_by(|left, right| left.id.cmp(&right.id));
    checks
}

fn check(id: &str, passed: bool) -> ReceiptCheck {
    ReceiptCheck {
        id: id.to_owned(),
        status: if passed {
            CheckStatus::Passed
        } else {
            CheckStatus::Failed
        },
        evidence_kind: "static".to_owned(),
        evidence_artifact: None,
        required: true,
    }
}

fn increment(counts: &mut BTreeMap<String, u64>, key: &str) -> Result<(), String> {
    let count = counts.entry(key.to_owned()).or_default();
    *count = count
        .checked_add(1)
        .ok_or_else(|| format!("count for `{key}` overflows u64"))?;
    Ok(())
}

fn usize_to_u64(field: &str, value: usize) -> Result<u64, String> {
    u64::try_from(value).map_err(|_| format!("{field} exceeds u64"))
}

fn sanitize_id(value: &str) -> String {
    value
        .chars()
        .map(|character| {
            if character.is_ascii_alphanumeric() || matches!(character, '-' | '_' | '.') {
                character
            } else {
                '-'
            }
        })
        .collect()
}

fn first_context<'a>(document: &'a Value, key: &str) -> Option<&'a str> {
    document
        .get("findings")?
        .as_array()?
        .iter()
        .find_map(|finding| finding.get("context")?.get(key)?.as_str())
}

fn field<'a>(object: &'a Map<String, Value>, name: &str) -> Result<&'a Value, String> {
    object
        .get(name)
        .ok_or_else(|| format!("control projection is missing `{name}`"))
}

fn object<'a>(value: &'a Value, role: &str) -> Result<&'a Map<String, Value>, String> {
    value
        .as_object()
        .ok_or_else(|| format!("control projection `{role}` must be an object"))
}

fn array<'a>(value: &'a Value, role: &str) -> Result<&'a [Value], String> {
    value
        .as_array()
        .map(Vec::as_slice)
        .ok_or_else(|| format!("control projection `{role}` must be an array"))
}

fn string<'a>(object: &'a Map<String, Value>, name: &str) -> Result<&'a str, String> {
    field(object, name)?
        .as_str()
        .ok_or_else(|| format!("control projection `{name}` must be a string"))
}

fn number(object: &Map<String, Value>, name: &str) -> Result<u64, String> {
    field(object, name)?
        .as_u64()
        .ok_or_else(|| format!("control projection `{name}` must be an unsigned integer"))
}

fn boolean(object: &Map<String, Value>, name: &str) -> Result<bool, String> {
    field(object, name)?
        .as_bool()
        .ok_or_else(|| format!("control projection `{name}` must be a boolean"))
}

