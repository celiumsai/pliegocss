import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  loadExternalAdoptionBundle,
  validateExternalAdoptionBundle,
} from "./external-adoption-v1.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = resolve(root, "docs", "product", "external-adoption-g7.md");
const siteOutputPath = resolve(root, "docs", "site", "external-adoption.md");

export function renderExternalAdoption(status) {
  const missing = status.missingCoverage.map((item) => `\`${item}\``).join(", ");
  return [
    "# G7 external adoption evidence",
    "",
    "<!-- Generated by scripts/render-external-adoption.mjs from the hash-bound external-adoption-v1 authority. Do not edit by hand. -->",
    "",
    `Status: **${status.result}**`,
    "",
    "G7 is an external-evidence gate, not a fixture-writing milestone. Its machine authority is",
    "[`benchmarks/external-adoption-v1/authority.json`](../../benchmarks/external-adoption-v1/authority.json).",
    "The public ledgers contain only consented, redacted, reviewed records; raw material remains in",
    "private custody and is represented by a stable SHA-256 digest.",
    "",
    "## Recruitment",
    "",
    `Recruitment is **${status.recruitment.status}**. The public cohort notice is`,
    `[GitHub issue #7](${status.recruitment.publicCohortUrl}). Apply privately through`,
    `[hello@pliegocss.dev](${status.recruitment.privateContact}) after reading the`,
    `[privacy notice](${status.recruitment.privacyNotice}). Public posts are recruitment signals`,
    "only and never count as consent or evidence.",
    "",
    "## Current qualified evidence",
    "",
    "| Evidence | Qualified | Required |",
    "| --- | ---: | ---: |",
    `| External interviews | ${status.counts.qualifiedInterviews} | ${status.thresholds.interviews.minimumQualified}–${status.thresholds.interviews.targetMaximum} |`,
    `| Real incidents | ${status.counts.qualifiedIncidents} | ${status.thresholds.incidents.minimumQualified} |`,
    `| Completed pilots | ${status.counts.qualifiedPilots} | ${status.thresholds.pilots.minimumQualified}–${status.thresholds.pilots.targetMaximum} |`,
    `| Independent projects | ${status.counts.independentProjects} | ${status.thresholds.pilots.minimumIndependentProjects} |`,
    `| Independent organizations | ${status.counts.independentOrganizations} | ${status.thresholds.pilots.minimumIndependentOrganizations} |`,
    "",
    `The adapter policy is **${status.policy.status}** for \`${status.policy.releaseLine}\`.`,
    `Missing promotion coverage: ${missing || "none"}.`,
    "",
    "## Admission boundary",
    "",
    "- Interviews count once per pseudonymous participant and require recorded research/public-summary consent.",
    "- Incidents must be observed in an external project. Synthetic conformance cases never count.",
    "- Pilots must complete adoption, browser equivalence, and exact rollback with zero blocking failures.",
    "- Pilot projects and organizations must be unique and outside Celiums/PliegoCSS ownership.",
    "- Every record requires an approved review, a redacted public entry, and a digest for its private source.",
    "- Draft notes, personal data, raw transcripts, access tokens, and proprietary source are never committed.",
    "",
    "The exact intake and custody workflow is documented in",
    "[`external-adoption-intake.md`](../contributing/external-adoption-intake.md). The promoted adapter",
    "scope is frozen in [`adapter-support-policy-0.1.x.json`](./adapter-support-policy-0.1.x.json).",
    "",
    "## Commands",
    "",
    "```console",
    "pnpm check:external-adoption-authority",
    "pnpm check:external-adoption",
    "```",
    "",
    "The first command validates an honest blocked or ready state. The second is a promotion gate and",
    "fails until every required coverage item is present.",
    "",
    "## Claim boundary",
    "",
    status.claimBoundary,
    "",
  ].join("\n");
}

