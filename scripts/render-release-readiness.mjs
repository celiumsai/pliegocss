import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { validateReleaseReadiness } from "./release-authority.mjs";

const root = resolve(import.meta.dirname, "..");
const sourcePath = resolve(root, "docs/product/release-readiness-0.1.0.json");
const outputPath = resolve(root, "docs/product/release-readiness-0.1.0.md");
const siteOutputPath = resolve(root, "docs/site/release-readiness.md");

function cell(value) {
  return String(value).replaceAll("|", "\\|").replaceAll("\n", " ");
}

function linkArtifact(artifact) {
  return `[${artifact.path}](${artifact.url}) — \`${artifact.sha256}\``;
}

export function renderReleaseReadiness(value) {
  const summary = validateReleaseReadiness(value, { root });
  const lines = [
    "# PliegoCSS 0.1.0 release readiness",
    "",
    "<!-- Generated by scripts/render-release-readiness.mjs from release-readiness-0.1.0.json. Do not edit by hand. -->",
    "",
    `Status: **${summary.result}**`,
    "",
    "This page is a deterministic projection of the schema-4",
    "[`release-readiness-0.1.0.json`](./release-readiness-0.1.0.json) machine authority.",
    "Historical reports and release notes do not change this state.",
    "",
    "## Candidate identity",
    "",
    "| Field | Value |",
    "| --- | --- |",
    `| Target | \`${cell(value.targetVersion)}\` |`,
    `| Candidate | \`${cell(value.candidateVersion)}\` |`,
    `| Tag | \`${cell(value.source.tag)}\` |`,
    `| Source commit | \`${cell(value.source.commit)}\` |`,
    `| Git tree | \`${cell(value.source.gitTree)}\` |`,
    `| Observed | \`${cell(value.observedAt)}\` |`,
    `| Expires | \`${cell(value.expiresAt)}\` |`,
    "",
    "## Readiness dimensions",
    "",
    "| Dimension | Ready |",
    "| --- | --- |",
    `| Technical | ${value.dimensions.technicalReady ? "yes" : "no"} |`,
    `| Operational | ${value.dimensions.operationallyReady ? "yes" : "no"} |`,
    `| Authorized | ${value.dimensions.authorized ? "yes" : "no"} |`,
    `| Promotion | ${value.dimensions.promotionReady ? "yes" : "no"} |`,
    "",
    "## Required checks",
    "",
    "| Check | Dimension | Status | Evidence | Coverage | Waiver |",
    "| --- | --- | --- | --- | ---: | --- |",
  ];
  for (const check of value.checks) {
    lines.push(
      `| \`${cell(check.id)}\` | ${cell(check.dimension)} | **${cell(check.status)}** | ${cell(check.evidenceClass)} | ${check.coveredCoverage.length}/${check.requiredCoverage.length} | ${check.waiverAdr ? `\`${cell(check.waiverAdr)}\`` : "none"} |`,
    );
  }
  lines.push("", "## Evidence and blockers", "");
  for (const check of value.checks) {
    lines.push(
      `### ${check.id}`,
      "",
      check.summary,
      "",
      `- Source: \`${check.source.commit}\` / tree \`${check.source.gitTree}\``,
      `- Validity: \`${check.observedAt}\` → \`${check.expiresAt}\``,
      `- Required coverage: ${check.requiredCoverage.map((item) => `\`${item}\``).join(", ")}`,
      `- Covered: ${check.coveredCoverage.length === 0 ? "none" : check.coveredCoverage.map((item) => `\`${item}\``).join(", ")}`,
    );
    if (check.artifacts.length > 0) {
      lines.push("- Hashed artifacts:");
      for (const artifact of check.artifacts) lines.push(`  - ${linkArtifact(artifact)}`);
    } else {
      lines.push("- Hashed artifacts: none");
    }
    if (check.references.length > 0) {
      lines.push("- References:");
      for (const reference of check.references) {
        lines.push(`  - [${reference.kind}](${reference.url})`);
      }
    }
    lines.push("");
  }
  lines.push(
    "## Promotion rule",
    "",
    value.promotionRule,
    "",
    "Archived snapshots are indexed under [`../archive/`](../archive/README.md).",
    "",
  );
  return lines.join("\n");
}

export function renderSiteReleaseReadiness(value) {
  const summary = validateReleaseReadiness(value, { root });
  const dimensions = [
    ["Technical", value.dimensions.technicalReady],
    ["Operational", value.dimensions.operationallyReady],
    ["Authorized", value.dimensions.authorized],
    ["Promotion", value.dimensions.promotionReady],
  ]
    .map(([label, ready]) => `${label}: ${ready ? "ready" : "blocked"}`)
    .join("; ");
  const blockers = value.checks
    .filter((check) => check.status !== "passed")
    .map((check) => `${check.id} (${check.status}): ${check.summary}`)
    .join(" ");
  return [
    "<!-- pliegocss-site",
    JSON.stringify({
      schemaVersion: 1,
      route: "/docs/release-readiness/",
      category: "Evidence",
      eyebrow: "Release readiness",
      order: 30,
    }),
    "-->",
    "",
    "# Release truth bound to one exact candidate.",
    "",
    `The current ${value.targetVersion} promotion state is ${summary.result}; no historical report can override these source-bound gates.`,
    "",
    "## Candidate identity {#candidate}",
    "",
    `Target ${value.targetVersion}; candidate ${value.candidateVersion}; tag ${value.source.tag}; commit ${value.source.commit}; Git tree ${value.source.gitTree}; observed ${value.observedAt}; expires ${value.expiresAt}.`,
    "",
    "## Readiness dimensions {#dimensions}",
    "",
    `${dimensions}.`,
    "",
    "## Current blockers {#blockers}",
    "",
    blockers || "No blockers remain in the machine authority.",
    "",
  ].join("\n");
}

const args = process.argv.slice(2);
if (args.length > 1 || (args[0] && !["--check", "--write"].includes(args[0]))) {
  throw new Error(`usage: node scripts/render-release-readiness.mjs [--check|--write]`);
}
const mode = args[0] ?? "--check";
const document = JSON.parse(readFileSync(sourcePath, "utf8"));
const rendered = renderReleaseReadiness(document);
const siteRendered = renderSiteReleaseReadiness(document);
if (mode === "--write") {
  writeFileSync(outputPath, rendered, "utf8");
  writeFileSync(siteOutputPath, siteRendered, "utf8");
  process.stdout.write(`wrote ${outputPath}\nwrote ${siteOutputPath}\n`);
} else {
  const current = readFileSync(outputPath, "utf8").replaceAll("\r\n", "\n");
  if (current !== rendered) {
    throw new Error("release readiness Markdown drifted; run with --write");
  }
  const siteCurrent = readFileSync(siteOutputPath, "utf8").replaceAll("\r\n", "\n");
  if (siteCurrent !== siteRendered) {
    throw new Error("site release readiness Markdown drifted; run with --write");
  }
  process.stdout.write("release readiness Markdown projections: current\n");
}
