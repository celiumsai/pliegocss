function filesBelow(directory) {
  return readdirSync(directory, { withFileTypes: true })
    .sort((left, right) => left.name.localeCompare(right.name, "en"))
    .flatMap((entry) => {
      const path = join(directory, entry.name);
      return entry.isDirectory() ? filesBelow(path) : [path];
    });
}

function splitMakeWords(value) {
  const words = [];
  let current = "";
  for (let index = 0; index < value.length; index += 1) {
    const character = value[index];
    if (character === "\\") {
      const next = value[index + 1];
      if (next === undefined) {
        throw new Error("rustc dep-info ended with an incomplete escape");
      }
      if (/\s/u.test(next)) {
        current += next;
        index += 1;
      } else {
        // rustc emits native Windows separators without Make escaping. Normalize those while
        // retaining the only escape needed by accepted project paths: escaped whitespace.
        current += "/";
      }
    } else if (/\s/u.test(character)) {
      if (current.length > 0) {
        words.push(current);
        current = "";
      }
    } else {
      current += character;
    }
  }
  if (current.length > 0) {
    words.push(current);
  }
  return words;
}

function depInfoPath(artifact) {
  const candidates = new Set();
  for (const filename of artifact.filenames ?? []) {
    const extension = extname(filename);
    let stem = basename(filename, extension);
    if (stem.startsWith("lib")) {
      stem = stem.slice(3);
    }
    candidates.add(join(dirname(filename), `${stem}.d`));
    candidates.add(join(dirname(filename), "deps", `${artifact.target.name}.d`));
  }
  const existing = [...candidates].filter(existsSync);
  if (existing.length !== 1) {
    throw new Error(
      `Cargo target ${artifact.target.name} did not resolve to exactly one rustc dep-info file: ${JSON.stringify(existing)}`,
    );
  }
  return existing[0];
}

function sourceUnitsFromDepInfo(artifact, sourceRoot) {
  const depInfo = readFileSync(depInfoPath(artifact), "utf8").replace(/\\\r?\n/gu, "");
  const firstRule = depInfo.split(/\r?\n\r?\n/u, 1)[0];
  const separator = firstRule.indexOf(": ");
  if (separator < 0) {
    throw new Error(`rustc dep-info for ${artifact.target.name} has no first rule`);
  }
  const units = splitMakeWords(firstRule.slice(separator + 2))
    .filter((path) => path.endsWith(".rs"))
    .map((path) => (isAbsolute(path) ? resolve(path) : resolve(sourceRoot, path)))
    .map((path) => {
      const logical = relative(fixtureRoot, path).replaceAll("\\", "/");
      if (
        logical === "" ||
        logical.startsWith("../") ||
        logical.includes("/../") ||
        isAbsolute(logical) ||
        !existsSync(path)
      ) {
        throw new Error(
          `Cargo target ${artifact.target.name} references an unsafe Rust source ${path}`,
        );
      }
      return logical;
    });
  const canonical = [...new Set(units)].sort((left, right) => left.localeCompare(right, "en"));
  if (canonical.length === 0) {
    throw new Error(`Cargo target ${artifact.target.name} has no Rust source units`);
  }
  return canonical;
}

function cargoTargetSources(specification) {
  const output = cargo([
    "check",
    "--locked",
    "--manifest-path",
    fixture,
    ...specification.arguments,
    "--message-format=json",
  ]);
  const artifacts = output
    .split(/\r?\n/u)
    .filter(Boolean)
    .map((line) => JSON.parse(line))
    .filter(
      (message) =>
        message.reason === "compiler-artifact" &&
        message.target?.name === specification.targetName &&
        resolve(message.target.src_path) === resolve(specification.srcPath) &&
        message.profile?.test === false,
    );
  if (artifacts.length !== 1) {
    throw new Error(
      `Cargo source target ${specification.id} resolved to ${artifacts.length} artifacts`,
    );
  }
  return {
    id: specification.id,
    sourceUnits: sourceUnitsFromDepInfo(artifacts[0], specification.sourceRoot),
  };
}

