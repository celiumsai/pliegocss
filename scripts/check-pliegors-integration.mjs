function cargoSourceInventoryDigest(inventory) {
  const hash = createHash("sha256");
  hash.update(`${JSON.stringify(inventory)}\n`);
  for (const logical of inventory.sourceUnits) {
    hash.update(logical);
    hash.update("\0");
    hash.update(readFileSync(join(fixtureRoot, ...logical.split("/"))));
    hash.update("\0");
  }
  return hash.digest("hex");
}

