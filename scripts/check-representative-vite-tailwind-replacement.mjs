import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { cargoTargetRoot } from "./rust-target.mjs";

const root = resolve(import.meta.dirname, "..");
const source = resolve(root, "integration-tests/representative/vite-tailwind-inventory");
const stage = resolve(root, "target/tests/vite-tailwind-plan-replacement");
const binary = resolve(cargoTargetRoot(root), "debug", process.platform === "win32" ? "pliego-cssc.exe" : "pliego-cssc");
const run = (args, cwd = stage) => {
  const result = spawnSync(binary, args, { cwd, encoding: "utf8" });
  if (result.status !== 0) throw new Error(`${args.join(" ")} failed:\n${result.stderr}`);
  return result.stdout;
};
const sha = (bytes) => createHash("sha256").update(bytes).digest("hex");
rmSync(stage, { recursive: true, force: true });
mkdirSync(stage, { recursive: true });
cpSync(source, stage, { recursive: true });
const originalInventory = JSON.parse(run(["migration-project-inventory", "."]));
const originalSource = originalInventory.sources.find((item) => item.file === "src/app.css");
const plan = JSON.parse(run(["migration-project-plan", "."]));
const proposal = plan.proposals.find((item) => item.kind === "replace");
if (!proposal || proposal.automatic !== false || proposal.file !== "src/app.css") throw new Error("replacement proposal absent or unsafe");
const before = readFileSync(resolve(stage, proposal.file));
if (sha(before) !== proposal.beforeSha256) throw new Error("before bytes disagree with plan");
const after = Buffer.concat([before, Buffer.from("/* PliegoCSS migration prepared */\n")]);
if (sha(after) !== proposal.afterSha256) throw new Error("after bytes disagree with plan");
writeFileSync(resolve(stage, "before.css"), before);
writeFileSync(resolve(stage, "after.css"), after);
run(["migration-replace-apply", "--file", proposal.file, "--before", "before.css", "--after", "after.css", "--receipt", "receipt.json"]);
const appliedInventory = JSON.parse(run(["migration-project-inventory", "."]));
const appliedSource = appliedInventory.sources.find((item) => item.file === proposal.file);
if (appliedSource.sourceSha256 !== proposal.afterSha256) throw new Error("applied inventory disagrees with plan");
run(["migration-replace-rollback", "--file", proposal.file, "--receipt", "receipt.json"]);
const rolledBackInventory = JSON.parse(run(["migration-project-inventory", "."]));
const rolledBackSource = rolledBackInventory.sources.find((item) => item.file === proposal.file);
if (JSON.stringify(rolledBackSource) !== JSON.stringify(originalSource)) throw new Error("rollback source inventory differs from original");
rmSync(stage, { recursive: true, force: true });
process.stdout.write(`${JSON.stringify({ schemaVersion: 1, fixture: "vite-tailwind-inventory-copy", proposal, appliedInventorySha256: appliedSource.sourceSha256, rolledBackSourceInventoryIdentical: true }, null, 2)}\n`);
